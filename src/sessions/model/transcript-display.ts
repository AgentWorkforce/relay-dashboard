// Ported from AgentWorkforce/cloud packages/web (hosted sessions dashboard).
// Keep behavior in sync with the hosted transcript renderer.
import { sanitizeCodexPromptDisplay } from "./codex-prompt-display";

/**
 * How one recorded user-role message appears in a transcript. Harnesses inject
 * context, hook output, and command plumbing as user-role text; none of it is
 * something the person typed, so it never renders as a raw prompt.
 */
export type UserMessageDisplay =
  | { kind: "hidden" }
  | { kind: "prompt"; text: string; attachments: string[] }
  | { kind: "interrupted" }
  | { kind: "notice"; text: string; output: string | null }
  | { kind: "shell"; command: string; output: string | null };

// Codex contextual fragments, delimited by open and close markers
// (case-insensitive). codex-rs/thread-store/src/local/rollout_migration/rollback.rs
const CODEX_CONTEXT_FRAGMENTS: [string, string][] = [
  ["# AGENTS.md instructions", "</INSTRUCTIONS>"],
  ["<environment_context>", "</environment_context>"],
  ["<user_instructions>", "</user_instructions>"],
  ["<skill>", "</skill>"],
  ["<user_shell_command>", "</user_shell_command>"],
  ["<subagent_notification>", "</subagent_notification>"],
  ["<recommended_plugins>", "</recommended_plugins>"],
  ["<goal_context>", "</goal_context>"],
  ["<codex_internal_context", "</codex_internal_context>"],
  ["<agent_message_board_notification>", "</agent_message_board_notification>"],
  ["<hook_prompt", "</hook_prompt>"],
  ["<app-context>", "</app-context>"],
  ["<in-app-browser-context", "</in-app-browser-context>"],
];
const CODEX_EXTERNAL_FRAGMENT = /^<external_([\w-]+)>[\s\S]*?<\/external_\1>/i;
const CODEX_INJECTED_WARNINGS = [
  "Warning: The maximum number of unified exec processes you can keep open is",
  "Warning: Your account was flagged for potentially high-risk cyber activity",
  "Warning: apply_patch was requested via ",
];
const CODEX_COMPACTION_PREFIX =
  "Another language model started to solve this problem";

// Claude Code wrappers whose content is never the person's own words.
const CLAUDE_HIDDEN_BLOCKS = [
  "system-reminder",
  "task-notification",
  "local-command-caveat",
  "user-prompt-submit-hook",
  "ide_opened_file",
  "ide_selection",
  "ide_diagnostics",
  "command-message",
];
// Claude Code records these user-role messages as metadata (`isMeta`): skill
// expansions, image dimensions, and messages relayed from other sessions.
const CLAUDE_META_PREFIXES = [
  "# Environment\nYou have been invoked in the following environment:",
  "The user hasn't heard from you in a while — say in a few words what you're doing, then continue.",
  "Caveat: The messages below were generated by the user while running local commands.",
  "Base directory for this skill:",
  "[Image: source:",
  "[Image: original ",
  "Another Claude session sent a message:",
];
const INTERRUPTED = /^\[Request interrupted by user[^\]]*\]$/;
// eslint-disable-next-line no-control-regex -- strips recorded terminal escapes
const ANSI = /\u001b\[[0-9;?]*[ -/]*[@-~]/g;

function block(text: string, tag: string): string | null {
  const match = new RegExp(`<${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</${tag}>`, "i").exec(
    text,
  );
  return match ? (match[1] ?? "") : null;
}

function withoutBlocks(text: string, tags: string[]): string {
  return tags.reduce(
    (current, tag) =>
      current.replace(
        new RegExp(`<${tag}(?:\\s[^>]*)?>[\\s\\S]*?</${tag}>`, "gi"),
        "",
      ),
    text,
  );
}

/**
 * Remove complete Codex context fragments from the start of a message. Returns
 * null when a leading fragment never closes: a truncated recording of injected
 * context, which has no typed text to show.
 */
function withoutCodexContext(text: string): string | null {
  let rest = text;
  for (;;) {
    const lower = rest.toLowerCase();
    const fragment = CODEX_CONTEXT_FRAGMENTS.find(([open]) =>
      lower.startsWith(open.toLowerCase()),
    );
    if (fragment) {
      const end = lower.lastIndexOf(fragment[1].toLowerCase());
      if (end < 0) return null;
      rest = rest.slice(end + fragment[1].length).trim();
      if (fragment[0] === "<in-app-browser-context") {
        rest = rest.replace(/^## My request:\s*/, "");
      }
      continue;
    }
    const external = CODEX_EXTERNAL_FRAGMENT.exec(rest);
    if (external) {
      rest = rest.slice(external[0].length).trim();
      continue;
    }
    return rest;
  }
}

function isCodexNotice(text: string): boolean {
  return (
    CODEX_INJECTED_WARNINGS.some((prefix) => text.startsWith(prefix)) ||
    text.startsWith(CODEX_COMPACTION_PREFIX)
  );
}

/** Drop a hidden wrapper that opens but never closes (a truncated recording). */
function withoutUnclosed(text: string, tags: string[]): string {
  return tags.reduce((current, tag) => {
    // Injected wrappers start a line; a mention inside prose is kept.
    const open = new RegExp(`(?:^|\\n)[ \\t]*<${tag}(?:\\s[^>]*)?>`, "i").exec(current);
    return open ? current.slice(0, open.index) : current;
  }, text);
}

function output(text: string | null): string | null {
  const clean = text?.replace(ANSI, "").trim();
  return clean ? clean : null;
}

export function displayUserMessage(content: string | null): UserMessageDisplay {
  if (!content) return { kind: "hidden" };
  let text = sanitizeCodexPromptDisplay(content).trim();
  if (!text) return { kind: "hidden" };
  if (INTERRUPTED.test(text) || /^<turn_aborted>/i.test(text))
    return { kind: "interrupted" };
  const typed = withoutCodexContext(text);
  if (typed === null || isCodexNotice(typed)) return { kind: "hidden" };
  text = typed;
  if (!text) return { kind: "hidden" };

  if (/^<task-notification[\s>]/i.test(text)) {
    const notification = block(text, "task-notification");
    const summary = notification === null ? null : output(block(notification, "summary"));
    return summary
      ? { kind: "notice", text: summary, output: null }
      : { kind: "hidden" };
  }

  const bashInput = block(text, "bash-input");
  if (bashInput !== null)
    return { kind: "shell", command: bashInput.trim(), output: null };
  const bashOutput = block(text, "bash-stdout") ?? block(text, "bash-stderr");
  if (bashOutput !== null) {
    const stderr = block(text, "bash-stderr");
    const combined = output(
      [block(text, "bash-stdout"), stderr].filter(Boolean).join("\n"),
    );
    return combined
      ? { kind: "notice", text: "Shell output", output: combined }
      : { kind: "hidden" };
  }

  const commandName = block(text, "command-name");
  if (commandName !== null) {
    const name = commandName.trim();
    const args = block(text, "command-args")?.trim();
    const command = `${name.startsWith("/") ? "" : "/"}${name}${args ? ` ${args}` : ""}`;
    return { kind: "prompt", text: command, attachments: [] };
  }

  const stdout =
    block(text, "local-command-stdout") ?? block(text, "local-command-stderr");
  if (stdout !== null) {
    const result = output(stdout);
    return result
      ? { kind: "notice", text: result, output: null }
      : { kind: "hidden" };
  }

  // Codex desktop prefixes attachments: "# Files mentioned by the user:"
  // sections, then "## My request:" with the typed text, then image tags.
  const attachments: string[] = [];
  const request = /^# Files mentioned by the user:[\s\S]*?\n## My request(?: for Codex)?:\n/.exec(text);
  if (request) text = text.slice(request[0].length);
  text = text.replace(
    /<image name=(\[[^\]]+\])[^>]*>\s*<\/image>/gi,
    (_match, name: string) => {
      attachments.push(name);
      return "";
    },
  );

  text = withoutUnclosed(withoutBlocks(text, CLAUDE_HIDDEN_BLOCKS), CLAUDE_HIDDEN_BLOCKS)
    // Pasted text is the person's input; keep it without its wrapper.
    .replace(/<pasted_content(?:\s[^>]*)?>([\s\S]*?)<\/pasted_content>/gi, "$1")
    .replace(/<\/?image>/gi, "")
    .trim();
  if (CLAUDE_META_PREFIXES.some((prefix) => text.startsWith(prefix)))
    return { kind: "hidden" };
  if (!text && !attachments.length) return { kind: "hidden" };
  return { kind: "prompt", text, attachments };
}

/** Recorded context stays inspectable behind a disclosure, never a user bubble. */
export function isSystemContext(content: string | null): boolean {
  const text = content?.trim() ?? "";
  if (displayUserMessage(content).kind !== "hidden") return false;
  return CODEX_CONTEXT_FRAGMENTS.some(([open]) => text.toLowerCase().startsWith(open.toLowerCase()))
    || /^<(?:system-reminder|in-app-browser-context)[\s>]/i.test(text)
    || text.startsWith("# Environment\nYou have been invoked in the following environment:");
}

// The envelope Agent Relay puts around a relayed message or a spawned agent's
// task: the `[via Agent Relay — …]` line, the `[report: …]`, `[agents: …]` or
// `[reply: …]` command lines, and the sentence telling a spawned agent how to
// report. relay-desktop probe/src/relay/spawn/report_back.rs
const RELAY_HEADER = /^\[via Agent Relay [—-] [^\]\n]*\]/;
const RELAY_SPAWNED = /spawned as @([^\s(·\]]+)/;
const RELAY_TRUNCATED_SPAWN = /^\[via Agent Relay [—-] spawned as @([^\s(·\]]+)/;
const RELAY_HINT = /^\s*\[(?:report|agents|reply|conductor): [^\]\n]*\]/;
const RELAY_ASK =
  /^\s*(?:@\S+ asked for this work\.[\s\S]*?cannot reach them\.(?:\s+(?:If you send them nothing, your final reply is sent to them\.|They receive only what you send them this way\.))?|To message another agent, send with the report command[\s\S]*?agents command\.)/;
// A summary cut off inside the envelope has no task left in it.
const RELAY_CUT = /^\s*(?:\[(?:report|agents|reply|conductor):|@\S+ asked for this work\.|To message another agent, )/;
const RELAY_INSTRUCTION_PREFIXES = ["[report:", "[agents:", "[reply:", "[conductor:", "To message another agent, "];
const RELAY_IDLE = "You were started by Agent Relay with no task yet. Wait for a message.";

function cutInsideRelayInstruction(text: string): boolean {
  const fragment = text.trim();
  if (!fragment) return false;
  if (RELAY_INSTRUCTION_PREFIXES.some((prefix) => prefix.startsWith(fragment))) return true;
  const asked = /^@\S+\s+(.+)$/.exec(fragment);
  return Boolean(asked && "asked for this work.".startsWith(asked[1]));
}

/**
 * The text after a leading Agent Relay envelope, and the agent a spawn named,
 * or null when `text` does not start with one. It reads the multi-line prompt
 * and the whitespace-collapsed summary of it alike.
 */
export function withoutRelayEnvelope(
  text: string,
): { text: string; agent: string | null } | null {
  const trimmed = text.trimStart();
  const header = RELAY_HEADER.exec(trimmed);
  if (!header) {
    // History's 240-character summary can end inside a long spawn header.
    // The generated spawn prefix still identifies the agent, but there is no
    // task text to extract from an unfinished header.
    const spawned = RELAY_TRUNCATED_SPAWN.exec(trimmed);
    return spawned && !trimmed.split("\n", 1)[0].includes("]")
      ? { text: "", agent: spawned[1] }
      : null;
  }
  let rest = trimmed.slice(header[0].length);
  for (let hint = RELAY_HINT.exec(rest); hint; hint = RELAY_HINT.exec(rest))
    rest = rest.slice(hint[0].length);
  rest = rest.replace(RELAY_ASK, "").trim();
  if (rest === RELAY_IDLE || RELAY_CUT.test(rest) || cutInsideRelayInstruction(rest)) rest = "";
  return { text: rest, agent: RELAY_SPAWNED.exec(header[0])?.[1] ?? null };
}

/**
 * A prompt as a title: the task inside an Agent Relay envelope, else the name
 * of the agent it spawned, else the prompt as it is.
 */
export function promptTitleText(text: string): string {
  const relayed = withoutRelayEnvelope(text);
  if (!relayed) return text;
  return relayed.text || relayed.agent || text;
}

/** One-line label for a session or prompt, or null when nothing was typed. */
export function displayPromptTitle(content: string | null): string | null {
  const display = displayUserMessage(content);
  return display.kind === "prompt"
    ? promptTitleText(display.text).replace(/\s+/g, " ").trim() || null
    : null;
}
