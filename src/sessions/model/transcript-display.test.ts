// Ported from AgentWorkforce/cloud packages/web (hosted sessions dashboard).
// Keep behavior in sync with the hosted transcript renderer.
import { describe, expect, it } from "vitest";
import { displayPromptTitle, displayUserMessage, promptTitleText } from "./transcript-display";

describe("displayUserMessage", () => {
  it.each([
    "# Environment\nYou have been invoked in the following environment: \n - Primary working directory: ~/work\n\nYou are powered by the model named Opus.",
    "The user hasn't heard from you in a while — say in a few words what you're doing, then continue.",
    "<environment_context>\n  <cwd>/work</cwd>\n</environment_context>",
    "<user_instructions>Be terse.</user_instructions>",
    "<skill>\n<name>ship</name>\n</skill>",
    "<subagent_notification>{}</subagent_notification>",
    "<external_codex_apps_open_page>{\"page_id\":null}</external_codex_apps_open_page>",
    "<hook_prompt hook_run_id=\"h1\">lint</hook_prompt>",
    "# AGENTS.md instructions for /work\n\n<INSTRUCTIONS>\nRules\n</INSTRUCTIONS>",
    "Warning: apply_patch was requested via exec_command. Use the apply_patch tool instead of exec_command.",
    "<system-reminder>\nWorktree: /tmp/w\n</system-reminder>",
    "<local-command-caveat>Caveat: generated locally.</local-command-caveat>",
    "<local-command-stdout></local-command-stdout>",
    "<task-notification><status>done</status></task-notification>",
    "Caveat: The messages below were generated by the user while running local commands. DO NOT respond.",
  ])("hides injected context: %s", (content) => {
    expect(displayUserMessage(content)).toEqual({ kind: "hidden" });
  });

  it("removes ambient browser state while preserving the actual request", () => {
    const context = '<in-app-browser-context source="ambient-ui-state">Current URL: http://localhost:3201/cloud</in-app-browser-context>';
    expect(displayUserMessage(`${context}\n## My request:\nFix scrolling`)).toEqual({ kind: "prompt", text: "Fix scrolling", attachments: [] });
    expect(displayUserMessage('<in-app-browser-context>truncated')).toEqual({ kind: "hidden" });
    expect(displayUserMessage('Explain <in-app-browser-context> tags')).toMatchObject({ text: 'Explain <in-app-browser-context> tags' });
  });

  it("keeps the typed request after stripped wrappers", () => {
    expect(
      displayUserMessage(
        "<system-reminder>\nYou are in a worktree.\n</system-reminder>\n\nFix the flaky test",
      ),
    ).toEqual({ kind: "prompt", text: "Fix the flaky test", attachments: [] });
    expect(
      displayUserMessage('<pasted_content id="a1">\nline one\n</pasted_content>\nand ship it'),
    ).toMatchObject({ text: "line one\n\nand ship it" });
  });

  it("renders slash commands as the command the person typed", () => {
    expect(
      displayUserMessage(
        "<command-message>model</command-message>\n<command-name>/model</command-name>\n<command-args>opus</command-args>",
      ),
    ).toEqual({ kind: "prompt", text: "/model opus", attachments: [] });
  });

  it("shows local command output and shell-mode commands", () => {
    expect(
      displayUserMessage("<local-command-stdout>Set model to \u001b[1mopus\u001b[22m</local-command-stdout>"),
    ).toEqual({ kind: "notice", text: "Set model to opus", output: null });
    expect(displayUserMessage("<bash-input>git status</bash-input>")).toEqual({
      kind: "shell",
      command: "git status",
      output: null,
    });
    expect(
      displayUserMessage("<bash-stdout>clean</bash-stdout><bash-stderr></bash-stderr>"),
    ).toEqual({ kind: "notice", text: "Shell output", output: "clean" });
  });

  it("summarizes task notifications that carry a summary", () => {
    expect(
      displayUserMessage(
        "<task-notification>\n<summary>Background build finished</summary>\n</task-notification>",
      ),
    ).toEqual({ kind: "notice", text: "Background build finished", output: null });
  });

  it("marks interruptions like Codex's turn_aborted notice", () => {
    expect(displayUserMessage("[Request interrupted by user for tool use]")).toEqual({
      kind: "interrupted",
    });
    expect(displayUserMessage("<turn_aborted>\nInterrupted\n</turn_aborted>")).toEqual({
      kind: "interrupted",
    });
  });

  it("separates Codex desktop attachments from the request", () => {
    expect(
      displayUserMessage(
        '\n# Files mentioned by the user:\n\n## shot.png: /tmp/shot.png\nImage attachment: true\n\n## My request:\nmatch this layout\n\n<image name=[Image #1] path="/tmp/shot.png">\n</image>',
      ),
    ).toEqual({ kind: "prompt", text: "match this layout", attachments: ["[Image #1]"] });
  });

  it("keeps prose that only mentions a tag", () => {
    expect(displayUserMessage("Explain what <system-reminder> blocks do")).toEqual({
      kind: "prompt",
      text: "Explain what <system-reminder> blocks do",
      attachments: [],
    });
  });
});

describe("displayPromptTitle", () => {
  it("returns the typed text on one line, or null when nothing was typed", () => {
    expect(
      displayPromptTitle("<system-reminder>x</system-reminder>\nRefactor\n  the parser"),
    ).toBe("Refactor the parser");
    expect(displayPromptTitle("<environment_context></environment_context>")).toBeNull();
  });
});

describe("review regressions", () => {
  it("strips leading Codex context and keeps the typed request", () => {
    expect(
      displayUserMessage("<environment_context><cwd>/work</cwd></environment_context>\nFix tests"),
    ).toEqual({ kind: "prompt", text: "Fix tests", attachments: [] });
  });

  it.each([
    "<system-reminder>\nWorktree: /tmp/w\nInstructions that were cut o",
    "<task-notification>\n<status>completed</sta",
    "<environment_context>\n  <cwd>/wo",
    "[Image: source: /tmp/shot.png]",
    "Another Claude session sent a message:\nhello",
  ])("hides truncated or metadata-only records: %s", (content) => {
    expect(displayUserMessage(content)).toEqual({ kind: "hidden" });
  });

  it("drops an unclosed wrapper after typed text", () => {
    expect(displayUserMessage("Ship it\n<system-reminder>cut o")).toMatchObject({ text: "Ship it" });
  });
});

describe("Agent Relay envelope titles", () => {
  const spawned =
    "[via Agent Relay — spawned as @history-search-degrade-fix-c (history-search-degrade-fix-c@finn-mac-mini-desktop) · from @devopsgrok · ref 15b05bf5ba73]\n" +
    "[report: printf '%s' 'your report' | curl -s --unix-socket '/run/relay.sock' 'http://relay/send?to=devopsgrok' --data-binary @-]\n" +
    "[agents: curl -s --unix-socket '/run/relay.sock' http://relay/agents]\n" +
    "@devopsgrok asked for this work. When you finish, or if you are blocked, send them your result with the report command. Your own tools (such as SendMessage) cannot reach them. If you send them nothing, your final reply is sent to them.\n\n" +
    "Fix the history search degrade path\n\nMore detail.";

  it("titles a spawned session by its task", () => {
    expect(displayPromptTitle(spawned)).toBe("Fix the history search degrade path More detail.");
    expect(promptTitleText(spawned.replace(/\s+/g, " "))).toBe("Fix the history search degrade path More detail.");
    expect(
      displayPromptTitle("[via Agent Relay — spawned as @w1 (w1@mac-desktop) · ref 0123456789ab]\n\nFix CI"),
    ).toBe("Fix CI");
    expect(
      displayPromptTitle("[via Agent Relay — from @a to @b · message 1 · ref 0123456789ab]\n[reply: x]\nhello"),
    ).toBe("hello");
  });

  it("names the agent when the task is cut off or empty", () => {
    const cut = spawned.replace(/\s+/g, " ").slice(0, 240);
    expect(promptTitleText(cut)).toBe("history-search-degrade-fix-c");
    const longHeader = `[via Agent Relay — spawned as @worker (worker@${"host".repeat(80)}) · ref 0123456789ab]`;
    expect(promptTitleText(longHeader.slice(0, 240))).toBe("worker");
    expect(
      promptTitleText(
        "[via Agent Relay — spawned as @w1 (w1@mac-desktop) · ref 0123456789ab]\n\nYou were started by Agent Relay with no task yet. Wait for a message.",
      ),
    ).toBe("w1");
  });

  it("names the agent when a summary stops inside a relay instruction", () => {
    const cutInside = (fragment: string, hints = "") => {
      const start = "[via Agent Relay — spawned as @worker (worker@";
      const end = `) · ref 0123456789ab] ${hints}`;
      const host = "h".repeat(240 - start.length - end.length - fragment.length);
      return `${start}${host}${end}${fragment} and more`.slice(0, 240);
    };
    expect(promptTitleText(cutInside("[repor"))).toBe("worker");
    expect(promptTitleText(cutInside("@parent asked for this wor", "[report: x] "))).toBe("worker");
  });

  it("keeps a person's own bracketed text", () => {
    expect(promptTitleText("[via Agent Relay] is great")).toBe("[via Agent Relay] is great");
    expect(promptTitleText("[draft] Fix it")).toBe("[draft] Fix it");
  });
});
